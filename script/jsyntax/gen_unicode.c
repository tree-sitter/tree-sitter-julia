// gen_unicode: print the Unicode property tables the JuliaSyntax lexer kernel needs (general category,
// grapheme boundclass, indic conjunct break), read from the utf8proc inside Julia's libjulia-internal,
// i.e. exactly the data JuliaSyntax's lexer uses in Julia. Build with utf8proc.h of the same version.
//   cc -I<utf8proc> gen_unicode.c -L<julia>/lib/julia -ljulia-internal -o gen_unicode && ./gen_unicode > tables.h
#include <stdio.h>
#include <string.h>
#include <stdlib.h>
#include "utf8proc.h"

#define NCP 0x110000
static unsigned short val[NCP];

int main(void) {
    const char *v = utf8proc_version();
    char hv[32];
    snprintf(hv, sizeof hv, "%d.%d.%d", UTF8PROC_VERSION_MAJOR, UTF8PROC_VERSION_MINOR, UTF8PROC_VERSION_PATCH);
    if (strcmp(v, hv) != 0) { fprintf(stderr, "utf8proc %s in libjulia-internal, header %s\n", v, hv); return 1; }
    // value = category | boundclass << 5 | indic_conjunct_break << 10
    unsigned short uniq[256]; int nuniq = 0;
    for (int c = 0; c < NCP; c++) {
        const utf8proc_property_t *p = utf8proc_get_property(c);
        val[c] = (unsigned short)(p->category | p->boundclass << 5 | p->indic_conjunct_break << 10);
    }
    const utf8proc_property_t *p0 = utf8proc_get_property(NCP);  // out of range
    unsigned short oor = (unsigned short)(p0->category | p0->boundclass << 5 | p0->indic_conjunct_break << 10);
    static unsigned char idx[NCP];
    for (int c = 0; c < NCP; c++) {
        int k = 0;
        while (k < nuniq && uniq[k] != val[c]) k++;
        if (k == nuniq) { if (nuniq == 256) { fprintf(stderr, "too many values\n"); return 1; } uniq[nuniq++] = val[c]; }
        idx[c] = (unsigned char)k;
    }
    // two-stage table: pick the block size giving the smallest total
    int best = 0; size_t bestsz = (size_t)-1;
    for (int sh = 4; sh <= 9; sh++) {
        int bs = 1 << sh, nb = NCP >> sh, nu = 0;
        int *map = malloc(sizeof(int) * nb);
        for (int b = 0; b < nb; b++) {
            int u;
            for (u = 0; u < b; u++) if (map[u] == u && memcmp(idx + (size_t)u * bs, idx + (size_t)b * bs, bs) == 0) break;
            map[b] = (u < b) ? map[u] : b;
            if (map[b] == b) nu++;
        }
        size_t sz = (size_t)nb * (nu > 256 ? 2 : 1) + (size_t)nu * bs;
        if (sz < bestsz) { bestsz = sz; best = sh; }
        free(map);
    }
    int sh = best, bs = 1 << sh, nb = NCP >> sh, nu = 0;
    int *map = malloc(sizeof(int) * nb), *ord = malloc(sizeof(int) * nb);
    for (int b = 0; b < nb; b++) {
        int u;
        for (u = 0; u < nu; u++) if (memcmp(idx + (size_t)ord[u] * bs, idx + (size_t)b * bs, bs) == 0) break;
        if (u == nu) ord[nu++] = b;
        map[b] = u;
    }
    printf("// generated by gen_unicode.c from utf8proc %s (libjulia-internal): do not edit\n", v);
    printf("// value = category | boundclass << 5 | indic_conjunct_break << 10\n");
    printf("#define JSK_UC_SHIFT %d\n#define JSK_UC_OOR 0x%x\n", sh, oor);
    printf("static const unsigned short jsk_uc_values[%d] = {", nuniq);
    for (int k = 0; k < nuniq; k++) printf("%s0x%x", k ? "," : "", uniq[k]);
    printf("};\nstatic const %s jsk_uc_stage1[%d] = {", nu > 256 ? "unsigned short" : "unsigned char", nb);
    for (int b = 0; b < nb; b++) printf("%s%s%d", b ? "," : "", b % 32 ? "" : "\n", map[b]);
    printf("};\nstatic const unsigned char jsk_uc_stage2[%d] = {", nu * bs);
    for (int u = 0; u < nu; u++)
        for (int i = 0; i < bs; i++) printf("%s%s%d", (u || i) ? "," : "", ((u * bs + i) % 48) ? "" : "\n", idx[(size_t)ord[u] * bs + i]);
    printf("};\n");
    fprintf(stderr, "values %d, shift %d, blocks %d, bytes %zu\n", nuniq, sh, nu, bestsz);
    return 0;
}
