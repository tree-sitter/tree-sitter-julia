# gen_kinds.jl KERNEL.jl > kinds.h: JuliaSyntax Kind codes the scanner names, and the grammar class of
# every kind (kernel.jl's kind_class, i.e. JuliaSyntax's kind predicates), as C.
include(abspath(ARGS[1]))
using .JSynKernel: JS, CLASSES, kind_class
valid(k) = try; JS.Kind(string(k)) == k; catch; false; end   # registered kinds round-trip by name
kinds = [k for k in (reinterpret(JS.Kind, UInt16(i)) for i in 0:typemax(UInt16)) if valid(k)]
n = maximum(reinterpret(UInt16, k) for k in kinds) + 1
println("// generated by script/jsyntax/gen_kinds.jl from JuliaSyntax: do not edit")
for (i, c) in enumerate(CLASSES); println("#define JSK_C_$c $(i - 1)"); end
cname(s) = all(c -> isletter(c) || isdigit(c) || c == '_', s) && isascii(s) ? s : nothing
for k in kinds
    s = string(k); c = cname(s)
    c === nothing || startswith(s, "BEGIN_") || startswith(s, "END_") || println("#define JSK_K_$c $(reinterpret(UInt16, k))")
end
for (name, k) in [("DOT", JS.K"."), ("EQ", JS.K"="), ("ELEMENT_OF", JS.K"∈")]   # kinds without a C name
    println("#define JSK_K_$name $(reinterpret(UInt16, k))")
end
println("#define JSK_NKINDS $n")
cls = zeros(Int, n)
for k in kinds; cls[reinterpret(UInt16, k) + 1] = findfirst(==(kind_class(k)), CLASSES) - 1; end
print("static const uint8_t jsk_kind_class[JSK_NKINDS] = {")
for (i, c) in enumerate(cls); print(i == 1 ? "" : ",", (i - 1) % 40 == 0 ? "\n" : "", c); end
println("};")
# Tokenize's ASCII fast path for identifiers (lex_identifier): which ASCII characters continue one
t = JS.Tokenize.ascii_is_identifier_char
print("static const uint8_t jsk_ascii_identifier_char[128] = {")
for i in 1:128; print(i == 1 ? "" : ",", Int(t[i])); end
println("};")

# "Plain" ASCII characters per lexing context, derived from JuliaSyntax's lexer: the scanner may mark
# through them without asking the kernel. Strings (delim x triple x raw) and line comments: the character
# is always part of the token, whatever follows. Block comments: the comment always continues at least two
# characters past it, whatever precedes or follows (so `=` and `#` of `=#`/`#=` are not plain).
using .JSynKernel: string_token, token
const OUT = Int32[0, 0]
function strlen(s, delim, triple, raw)
    GC.@preserve s OUT begin
        k = string_token(pointer(s), ncodeunits(s), Int32(delim), triple, raw, Int32(0), pointer(OUT))
    end
    return OUT[1], reinterpret(JS.Kind, UInt16(k))
end
function toklen(s)
    GC.@preserve s OUT token(pointer(s), ncodeunits(s), Int32(0), pointer(OUT))
    return OUT[1]
end
const FOLLOW = [""; [string(Char(b)) for b in 0x00:0x7f]]
const FOLLOW2 = ["", "\"", "`", "'", "=", "#", "\n", "\r", "\\", "\$", " ", "a"]
function plain_string(c, delim, triple, raw)
    c == '\\' && return false
    for f1 in FOLLOW, f2 in FOLLOW2
        s = "ab" * c * f1 * f2
        len, k = strlen(s, delim, triple, raw)
        (k == JS.K"String" || k == JS.K"CmdString") && len >= 3 || return false
    end
    true
end
function plain_line_comment(c)
    for f1 in FOLLOW, f2 in FOLLOW2
        toklen("#ab" * c * f1 * f2 * "\n") >= 4 || return false
    end
    true
end
function plain_block_comment(c)
    for p1 in FOLLOW[2:end], f1 in FOLLOW[2:end], f2 in FOLLOW2[2:end]
        s = "#=a" * p1 * c * f1 * f2 * "zz=#"
        toklen(s) >= ncodeunits("#=a" * p1 * c * f1 * f2) || return false
    end
    true
end
println("// plain ASCII characters per context: JSK_PLAIN_STR(delim_is_backtick, triple, raw), line and block comments")
for (name, f) in [("str_q", c -> plain_string(c, '"', false, false)), ("str_qqq", c -> plain_string(c, '"', true, false)),
                  ("str_q_raw", c -> plain_string(c, '"', false, true)), ("str_qqq_raw", c -> plain_string(c, '"', true, true)),
                  ("cmd_b", c -> plain_string(c, '`', false, false)), ("cmd_bbb", c -> plain_string(c, '`', true, false)),
                  ("cmd_b_raw", c -> plain_string(c, '`', false, true)), ("cmd_bbb_raw", c -> plain_string(c, '`', true, true)),
                  ("line_comment", plain_line_comment), ("block_comment", plain_block_comment)]
    local t = [Int(f(Char(b))) for b in 0x00:0x7f]
    print("static const uint8_t jsk_plain_$name[128] = {")
    for i in 1:128; print(i == 1 ? "" : ",", t[i]); end
    println("};")
end
for (name, k) in [("DQUOTE", JS.K"\""), ("TRIPLE_DQUOTE", JS.K"\"\"\""), ("BACKTICK", JS.K"`"), ("TRIPLE_BACKTICK", JS.K"```"),
                  ("DOLLAR", JS.K"$"), ("PRIME", JS.K"'")]
    println("#define JSK_K_$name $(reinterpret(UInt16, k))")
end

# ---- grammar-tokens.js and externals.h (with ARGS[2], ARGS[3]): the scanner's token list ----
if length(ARGS) >= 3
    include(joinpath(dirname(abspath(ARGS[1])), "tokens.jl"))
    # JuliaSyntax's keywords that grammar.js uses (tree-sitter rejects unused external strings)
    grammar = read(joinpath(dirname(abspath(ARGS[2])), "grammar.js"), String)
    kwkinds = [k for k in kinds if (JS.is_keyword(k) || JS.is_word_operator(k)) && occursin("'$(k)'", grammar)]
    keywords = sort([string(k) for k in kwkinds])
    open(ARGS[2], "w") do io
        println(io, "// generated by script/jsyntax/gen_kinds.jl from script/jsyntax/tokens.jl and JuliaSyntax: do not edit")
        println(io, "// The scanner's tokens, in grammar.js externals order (grammar-tokens.js).")
        println(io, "module.exports = \$ => [")
        for t in SCANNER_TOKENS; println(io, "  \$.$t,"); end
        for (t, _) in SCANNER_STRINGS; println(io, "  '$t',"); end
        println(io, "  // keywords (JuliaSyntax: is_keyword, is_word_operator)")
        for k in keywords; println(io, "  '$k',"); end
        println(io, "];")
        println(io, "module.exports.keywords = [", join(("'$k'" for k in keywords), ", "), "];")
    end
    open(ARGS[3], "w") do io
        println(io, "// generated by script/jsyntax/gen_kinds.jl from script/jsyntax/tokens.jl and JuliaSyntax: do not edit")
        println(io, "// The scanner's tokens, in grammar.js externals order.")
        println(io, "enum TokenType {")
        for t in SCANNER_TOKENS; println(io, "    ", uppercase(lstrip(t, '_')), ","); end
        for (_, c) in SCANNER_STRINGS; println(io, "    ", c, ","); end
        for k in keywords; println(io, "    KW_", uppercase(k), ","); end
        println(io, "    TOKEN_COUNT_", ",")
        println(io, "};")
        println(io, "#define FIRST_KEYWORD KW_", uppercase(keywords[1]))
        println(io, "#define LAST_KEYWORD KW_", uppercase(keywords[end]))
        println(io, "static int keyword_symbol(int k) {")
        println(io, "    switch (k) {")
        for k in kwkinds; println(io, "        case $(reinterpret(UInt16, k)): return KW_$(uppercase(string(k))); // $k"); end
        println(io, "        default: return -1;")
        println(io, "    }")
        println(io, "}")
    end
end
